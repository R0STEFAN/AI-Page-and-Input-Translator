// scripts/build-content.js
// Bundles modular content scripts into a single classic script IIFE for Chrome MV3 content_scripts.

import fs from 'node:fs';
import path from 'node:path';

function stripImportsAndExports(code) {
  return code
    // Remove import statements (single or multi-line)
    .replace(/import\s+[\s\S]*?from\s+['"][^'"]+['"];?/g, '')
    // Remove export keyword before functions, async functions, const, let, var
    .replace(/export\s+async\s+function\s+/g, 'async function ')
    .replace(/export\s+function\s+/g, 'function ')
    .replace(/export\s+const\s+/g, 'const ')
    .replace(/export\s+let\s+/g, 'let ')
    .replace(/export\s+var\s+/g, 'var ')
    .trim();
}

export function buildContentBundle() {
  const contentDir = path.resolve('content');
  const files = [
    'detector.js',
    'walker.js',
    'replacer.js',
    'selection.js',
    'content.js'
  ];

  const sections = [];

  for (const file of files) {
    const filePath = path.join(contentDir, file);
    if (!fs.existsSync(filePath)) {
      throw new Error(`Source file missing: ${filePath}`);
    }
    const raw = fs.readFileSync(filePath, 'utf8');
    const cleaned = stripImportsAndExports(raw);
    sections.push(`  // ==========================================\n  // Module: ${file}\n  // ==========================================\n  ${cleaned.split('\n').join('\n  ')}`);
  }

  const bundle = `// AI Page Translator - Content Script Bundle (Classic IIFE for Chrome MV3)
// Auto-generated by scripts/build-content.js. Do not edit directly.

(() => {
  'use strict';

${sections.join('\n\n')}
})();
`;

  const outputPath = path.join(contentDir, 'content.bundle.js');
  fs.writeFileSync(outputPath, bundle, 'utf8');
  console.log(`Successfully built ${outputPath} (${bundle.length} bytes)`);
  return outputPath;
}

// Execute if run directly from CLI
if (process.argv[1] && process.argv[1].endsWith('build-content.js')) {
  try {
    buildContentBundle();
  } catch (err) {
    console.error('Failed to build content bundle:', err);
    process.exit(1);
  }
}
